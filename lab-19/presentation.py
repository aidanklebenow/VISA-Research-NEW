"""Plain-language explanations built from the saved financial evidence."""
import panel

LENSES = {
    'Buffett': ('Earning power', 'Does this business consistently earn profits and generate cash after capital spending?'),
    'Graham': ('Financial strength', 'Does the company have a liquidity cushion and a record of positive, growing earnings?'),
    'Burry': ('Cash quality', 'Does operating cash flow support reported earnings, and are liabilities reasonable relative to equity?'),
    'Cathie Wood': ('Growth and reinvestment', 'Has revenue grown quickly, and does reported research spending support further investigation?'),
}


def explained_checks(report, selected):
    rows = report['rows']
    last = rows[-1]

    def series(field):
        return '; '.join(f"{r['fiscal_year_end']}: {panel.display(field, r[field])}" for r in rows)

    def endpoints(field):
        return f"{panel.display(field, rows[0][field])} → {panel.display(field, last[field])}"

    definitions = {
        'Buffett': [
            ('Return on equity', 'Net income ÷ year-end equity measures profit relative to shareholder capital.', 'At least 15% in every annual period.', series('roe')),
            ('Positive owner earnings', 'Operating cash flow minus capital spending is the lab’s simplified owner-earnings measure.', 'Above zero in every annual period.', series('owner_earnings')),
            ('Growing owner earnings', 'Compare the first and last annual owner-earnings figures.', 'Last period exceeds the first; complete history required.', endpoints('owner_earnings')),
        ],
        'Graham': [
            ('Liquidity cushion', 'Current assets ÷ current liabilities compares near-term resources with near-term obligations.', 'Latest ratio at least 2.0 for the assignment baseline.', panel.display('current_ratio', last['current_ratio'])),
            ('Positive net income', 'Net income is the profit remaining after reported expenses.', 'Above zero in every annual period.', series('net_income')),
            ('Growing net income', 'Compare profit at the beginning and end of the annual history.', 'Last period exceeds the first; complete history required.', endpoints('net_income')),
        ],
        'Burry': [
            ('Cash supports earnings', 'Compare cash generated by operations with accounting profit in each annual period.', 'Operating cash flow at least net income in every period.', '; '.join(f"{r['fiscal_year_end']}: {panel.display('operating_cash_flow', r['operating_cash_flow'])} vs {panel.display('net_income', r['net_income'])}" for r in rows)),
            ('Liabilities relative to equity', 'Total liabilities ÷ equity measures obligations relative to the shareholder capital base.', 'Latest ratio no more than 2.0; equity must be positive.', panel.display('liabilities_equity', last['liabilities_equity'])),
        ],
        'Cathie Wood': [
            ('Revenue growth', 'Compound annual growth compares first and last revenue over four annual intervals.', 'At least 15% annual growth in the baseline.', panel.growth_display(report)),
            ('Reported research spending', 'Research and development expense ÷ revenue measures reported research intensity.', 'Latest ratio at least 5%; missing expense stays unknown.', panel.display('rd_revenue', last['rd_revenue'])),
        ],
    }
    output = []
    for name in selected:
        for definition, result in zip(definitions[name], report['panel'][name].values()):
            label, meaning, rule, observed = definition
            output.append({'Investor': name, 'Test': label, 'What it means': meaning,
                           'Passing rule': rule, 'Evidence from saved report': observed,
                           'Result': result.upper()})
    return output


